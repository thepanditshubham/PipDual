import { makeTicks } from './market';
import { rng } from './rng';
import type { MarketSegment } from './types';

const TAGS = ['trend_up', 'trend_down', 'range', 'spike', 'whipsaw', 'gap'] as const;
const DIFFICULTIES: Array<'easy' | 'medium' | 'hard'> = ['easy', 'medium', 'hard'];

/**
 * Generate 100 pre-seeded synthetic market segments for testing and default gameplay.
 * Each segment is tagged with a market behaviour and difficulty level.
 */
export function generateFixtures(): MarketSegment[] {
  const segments: MarketSegment[] = [];
  const rand = rng(777);

  for (let i = 0; i < 100; i++) {
    const seed = 10000 + i;
    const tagIndex = Math.floor(rand() * TAGS.length);
    const diffIndex = Math.floor(rand() * DIFFICULTIES.length);
    const tag = TAGS[tagIndex];
    const difficulty = DIFFICULTIES[diffIndex];

    const ticks = makeTicks(seed);

    segments.push({
      id: `synthetic-${String(i).padStart(3, '0')}`,
      title: `${formatTag(tag)} #${i + 1}`,
      asset: 'Synthetic',
      tags: [tag],
      difficulty,
      ticks,
      source: 'synthetic',
      licenseNote: 'Generated by Pip Duel engine',
      enabled: true,
    });
  }

  return segments;
}

function formatTag(tag: string): string {
  return tag
    .split('_')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

/** Get a segment by index (0-99) from the generated fixtures */
export function getFixtureSegment(index: number): MarketSegment {
  const fixtures = generateFixtures();
  return fixtures[Math.min(Math.max(0, index), fixtures.length - 1)];
}

/** Get a random fixture segment using a seed */
export function getRandomFixtureSegment(seed: number): MarketSegment {
  const rand = rng(seed);
  const index = Math.floor(rand() * 100);
  return getFixtureSegment(index);
}
